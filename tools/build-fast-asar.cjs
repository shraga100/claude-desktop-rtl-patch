'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/fast-asar.cjs'), 'utf8').replace(/\r\n/g, '\n').trimEnd();
if (/^'@/m.test(source)) throw new Error('PowerShell here-string terminator in helper');
const file = path.join(root, 'patch.ps1');
const patch = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
const start = '# BEGIN GENERATED FAST ASAR';
const end = '# END GENERATED FAST ASAR';
if (!patch.includes(start) || !patch.includes(end)) throw new Error('Missing fast-ASAR build markers');
const block = start + "\n$FAST_ASAR_CODE = @'\n" + source + "\n'@\n" + end;
fs.writeFileSync(file, patch.slice(0, patch.indexOf(start)) + block + patch.slice(patch.indexOf(end) + end.length));
console.log('Embedded fast-ASAR helper in patch.ps1; release signatures must be regenerated by the maintainer.');
